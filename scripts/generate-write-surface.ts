/**
 * Generate the `mutate` write surface from the generated SDK.
 *
 * The `mutate` tool's model-facing surface is an **explicit write allowlist** over
 * the generated `/v1` SDK — NOT a naive `POST/PUT/PATCH/DELETE` verb filter (some
 * POSTs are state-transition / computed actions, not data writes). This script:
 *
 *   1. Parses the do-not-edit `src/generated/sdk.gen.ts` (one block per operation:
 *      JSDoc summary + `export const <op> = … .<method>({ url: '<url>' … })`).
 *   2. Keeps ONLY allowlisted PATCH/PUT value updates. POST operations remain
 *      excluded until durable retry identity is enforced end-to-end; DELETE and
 *      destructive/lifecycle actions are excluded by construction. Fail-safe: a
 *      new write op is invisible until it is explicitly reviewed here.
 *   3. Emits three artifacts, all keyed off the SAME allowlist so they cannot
 *      drift from each other or from the real route set:
 *      - `src/mutate/write-surface.gen.ts`: the typed write-op METADATA table the
 *        generic dispatcher and the agent tool description consume.
 *      - `src/mutate/write-surface.interface.gen.ts`: the typed `WriteSurface`
 *        CONTRACT — one `<op>(data: <Op>Data): Promise<<Op>Response>` method per
 *        allowlisted op, request/response types imported from the generated
 *        `types.gen.ts`. This is the autogenerated interface an implementation
 *        must satisfy; when the OpenAPI (and thus the generated types) changes,
 *        the regenerated interface forces every `satisfies WriteSurface`
 *        implementation to update or fail `tsc`.
 *      - `src/mutate/write-surface.bridge.gen.ts`: `createBridgeWriteSurface`, a
 *        ready-made `WriteSurface` whose every method forwards its typed
 *        `{ path, body, query }` to the generic in-process dispatcher (the
 *        app.fetch bridge). Hosts compose this with hand-written native ops
 *        (e.g. the in-memory budget path) and `satisfies WriteSurface` proves the
 *        composition still covers the whole contract.
 *
 * Re-run after any SDK regeneration: pnpm generate:mutate
 *
 * The allowlist is the security boundary; everything else is derived from the
 * spec by code, so the surface cannot drift from the real route set.
 */

